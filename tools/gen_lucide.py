#!/usr/bin/env python3
"""Generate apps/light/src/lucide.rs (codepoints of the Lucide icons the UI uses) from assets/icons/info.json."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
NAMES = """folder folder-open play square rotate-cw search triangle-alert circle-x check chevron-right chevron-down chevron-up x
settings list-tree terminal trash-2 folder-tree git-branch info arrow-up arrow-down git-commit-horizontal refresh-cw
history ellipsis square-terminal palette keyboard code-xml pencil package cloud-download hammer file-text scroll-text
eraser globe chevron-left undo-2 file-diff container hard-drive-download circle-check-big loader-circle key-round user
lock book-marked puzzle eye columns-2 plus file-plus folder-plus folder-git-2 monitor arrow-left copy
scissors clipboard redo-2 log-out folder-search sun moon file""".split()

info = json.loads((ROOT / "assets" / "icons" / "info.json").read_text(encoding="utf-8"))
lines = ["//! Generated by tools/gen_lucide.py from Lucide (ISC license, see assets/icons/LICENSE). Do not edit.", ""]
for n in NAMES:
    if n not in info:
        raise SystemExit(f"unknown Lucide icon: {n}")
    code = int(info[n]["encodedCode"].lstrip("\\"), 16)
    lines.append("pub const %s: char = '\\u{%x}';" % (n.upper().replace("-", "_"), code))
(ROOT / "apps" / "light" / "src" / "lucide.rs").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {len(NAMES)} icons")
